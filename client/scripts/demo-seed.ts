/**
 * Exports the fictional demo data in src/data.js as the LMS API's demo seed
 * (../server/src/Lms.Api/Demo/demo-seed.json). In Demo mode the API serves
 * these people and classes as if they came from ISMS, and this content as if
 * instructors had created it, so the browser tests and demos run against a
 * real API with the familiar data.
 *
 *   npm run demo-seed          writes the file
 *   npm run demo-seed:check    fails when the file is out of date (CI)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { assessments, courses, materials, questionsByAssessment, students } from "../src/data.js";

const target = fileURLToPath(new URL("../../server/src/Lms.Api/Demo/demo-seed.json", import.meta.url));

const honorific = /^(Ms\.|Mr\.|Dr\.|Prof\.)\s*/;
// Same ids as the browser-local seed (roles/shared/lmsData.js): instructor-1…, s0…
const teacherNames = [...new Set(courses.map((course) => course.teacher))];
const instructors = teacherNames.map((name, index) => {
  const [firstName, ...rest] = name.replace(honorific, "").split(" ");
  return { id: `instructor-${index + 1}`, firstName, lastName: rest.join(" "), honorific: name.match(honorific)?.[1] ?? "" };
});

const seed = {
  note: "Generated by client/scripts/demo-seed.ts from client/src/data.js. Fictional data only. Do not edit by hand.",
  term: { schoolYear: "2026-2027", semester: "1st Semester" },
  instructors,
  students: students.map((student) => {
    const [firstName, ...rest] = student.name.split(" ");
    return { id: student.id, firstName, lastName: rest.join(" "), email: student.email };
  }),
  classes: courses.map((course, index) => ({
    id: course.id,
    subjectId: index + 1,
    code: course.code,
    name: course.name,
    section: course.section,
    instructorId: instructors[teacherNames.indexOf(course.teacher)]?.id ?? "",
  })),
  materials: materials.map((material) => ({
    classId: material.courseId,
    title: material.title,
    kind: material.kind,
    description: material.summary,
  })),
  coursework: assessments.map((assessment) => ({
    classId: assessment.courseId,
    title: assessment.title,
    category: assessment.type,
    description: assessment.description,
    instructions: assessment.instructions,
    dueAt: assessment.dueAt,
    timeLimitMinutes: Number.parseInt(assessment.timeLimit, 10) || null,
    questions: (questionsByAssessment[assessment.id] ?? []).map((question) => ({
      prompt: question.prompt,
      options: question.options,
      correct: question.correct,
      points: question.points,
      timeLimitSeconds: 60,
    })),
  })),
};

const json = `${JSON.stringify(seed, null, 2)}\n`;
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // missing counts as out of date
  }
  if (current !== json) {
    console.error("demo-seed.json is out of date. Run `npm run demo-seed` and commit the result.");
    process.exit(1);
  }
  console.log("Demo seed is up to date.");
} else {
  writeFileSync(target, json);
  console.log(`Wrote ${target}`);
}
